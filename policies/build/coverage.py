#!/usr/bin/env python3
"""Build policies/coverage.md from requirements.yaml and the policies' YAML front matter.

    python policies/build/coverage.py            # write coverage.md
    python policies/build/coverage.py --check    # exit 1 if coverage.md is stale or a policy cites an unknown ID

Importable too: load_policies(), build_coverage(), render_coverage().
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

import yaml

POLICIES_DIR = Path(__file__).resolve().parents[1]
REQUIREMENTS_FILE = POLICIES_DIR / "requirements.yaml"
COVERAGE_FILE = POLICIES_DIR / "coverage.md"
FRONT_MATTER = re.compile(r"\A---\n(.*?)\n---\n", re.DOTALL)
HEADER = "TEMPLATE. Adapt before adopting. Sections marked [HR or legal review] need a human reviewer."
REQUIRED_KEYS = ("id", "slug", "title", "version", "status", "owner_role", "approver_role", "review_cycle", "applies_to", "requirements")
REQUIRED_SECTIONS = (
    "## 1. Purpose",
    "## 2. Scope",
    "## 3. Roles and responsibilities",
    "## 4. Policy statements",
    "## 5. Exceptions",
    "## 6. Enforcement",
    "## 7. Review",
    "## 8. Related documents",
    "## 9. Revision history",
)
ALLOWED_PLACEHOLDERS = {
    "{{Company}}",
    "{{Security Lead}}",
    "{{CEO}}",
    "{{HR Lead}}",
    "{{IT Lead}}",
    "{{AI Lead}}",
    "{{Privacy Lead}}",
    "{{Finance Lead}}",
    "{{Effective Date}}",
}


@dataclass
class Policy:
    path: Path
    meta: dict
    body: str

    @property
    def id(self) -> str:
        return str(self.meta["id"])

    @property
    def title(self) -> str:
        return str(self.meta["title"])

    @property
    def requirements(self) -> dict[str, list[str]]:
        raw = self.meta.get("requirements") or {}
        return {framework: [str(x) for x in (ids or [])] for framework, ids in raw.items()}


@dataclass
class Coverage:
    frameworks: dict  # requirements.yaml content
    policies: list[Policy]
    by_requirement: dict[tuple[str, str], list[Policy]] = field(default_factory=dict)
    unknown: list[tuple[str, str, str]] = field(default_factory=list)  # (policy id, framework, requirement)

    def uncovered(self, framework: str) -> list[str]:
        return [rid for rid in self.frameworks[framework]["requirements"] if not self.by_requirement.get((framework, rid))]


def load_requirements(path: Path = REQUIREMENTS_FILE) -> dict:
    return yaml.safe_load(path.read_text(encoding="utf-8"))["frameworks"]


def policy_files(folder: Path = POLICIES_DIR) -> list[Path]:
    return sorted(p for p in folder.glob("[0-9][0-9]-*.md"))


def parse_policy(path: Path) -> Policy:
    text = path.read_text(encoding="utf-8")
    match = FRONT_MATTER.match(text)
    if not match:
        raise ValueError(f"{path.name}: no YAML front matter")
    meta = yaml.safe_load(match.group(1)) or {}
    return Policy(path=path, meta=meta, body=text[match.end():])


def load_policies(folder: Path = POLICIES_DIR) -> list[Policy]:
    return [parse_policy(p) for p in policy_files(folder)]


def build_coverage(frameworks: dict | None = None, policies: list[Policy] | None = None) -> Coverage:
    frameworks = frameworks if frameworks is not None else load_requirements()
    policies = policies if policies is not None else load_policies()
    coverage = Coverage(frameworks=frameworks, policies=policies)
    for policy in policies:
        for framework, ids in policy.requirements.items():
            known = frameworks.get(framework, {}).get("requirements", {})
            for rid in ids:
                if framework not in frameworks or rid not in known:
                    coverage.unknown.append((policy.id, framework, rid))
                    continue
                coverage.by_requirement.setdefault((framework, rid), []).append(policy)
    return coverage


def render_coverage(coverage: Coverage) -> str:
    out: list[str] = []
    out.append("# Policy coverage matrix\n")
    out.append("Generated by `policies/build/coverage.py` from `requirements.yaml` and each policy's front matter. Do not edit by hand.\n")
    out.append("IDs only; the one-line summaries are Alimi's own words, not the standards' text.\n")
    out.append("## Policies\n")
    out.append("| ID | Policy | File |")
    out.append("| --- | --- | --- |")
    for p in coverage.policies:
        out.append(f"| {p.id} | {p.title} | `{p.path.name}` |")
    out.append("")
    out.append("## Summary\n")
    out.append("| Framework | Requirements | Covered | Uncovered |")
    out.append("| --- | --- | --- | --- |")
    for framework, spec in coverage.frameworks.items():
        total = len(spec["requirements"])
        missing = coverage.uncovered(framework)
        out.append(f"| {spec['short']} | {total} | {total - len(missing)} | {len(missing)} |")
    out.append("")
    for framework, spec in coverage.frameworks.items():
        out.append(f"## {spec['name']}\n")
        out.append("| Requirement | What it is about (our words) | Policies |")
        out.append("| --- | --- | --- |")
        for rid, summary in spec["requirements"].items():
            policies = coverage.by_requirement.get((framework, rid), [])
            cell = ", ".join(p.id for p in policies) if policies else "**none**"
            out.append(f"| {rid} | {summary} | {cell} |")
        missing = coverage.uncovered(framework)
        out.append("")
        if missing:
            out.append(f"Uncovered in {spec['short']}: {', '.join(missing)}.\n")
        else:
            out.append(f"Every {spec['short']} requirement in the catalogue maps to at least one policy.\n")
    if coverage.unknown:
        out.append("## Unknown IDs cited by policies\n")
        for policy_id, framework, rid in coverage.unknown:
            out.append(f"- {policy_id} cites `{framework}: {rid}`, which is not in requirements.yaml")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="do not write; fail if coverage.md is stale or an unknown ID is cited")
    args = parser.parse_args(argv)
    coverage = build_coverage()
    text = render_coverage(coverage)
    problems = [f"{pid} cites unknown {fw} requirement {rid}" for pid, fw, rid in coverage.unknown]
    if args.check:
        current = COVERAGE_FILE.read_text(encoding="utf-8") if COVERAGE_FILE.exists() else ""
        if current != text:
            problems.append("coverage.md is stale; run python policies/build/coverage.py")
        for line in problems:
            print(f"error: {line}", file=sys.stderr)
        return 1 if problems else 0
    COVERAGE_FILE.write_text(text, encoding="utf-8")
    print(f"wrote {COVERAGE_FILE.relative_to(POLICIES_DIR.parent)}")
    for framework, spec in coverage.frameworks.items():
        missing = coverage.uncovered(framework)
        print(f"  {spec['short']}: {len(spec['requirements']) - len(missing)}/{len(spec['requirements'])} covered" + (f", uncovered: {', '.join(missing)}" if missing else ""))
    for line in problems:
        print(f"  warning: {line}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
